#!/usr/bin/env python3
"""Requirements traceability: SYS -> HLR -> tests (and HLR -> source).

Parses reqs/*.sdoc, extracts HLR-*/SYS-* tags from test docstrings (via ast)
and from source-code comments, then writes docs/trace/TRACEABILITY.md.

  trace.py          regenerate the matrix
  trace.py --check  regenerate and exit non-zero on any gap
                    (HLR with no test, SYS with no HLR, SYS with no test,
                     tag in tests/src that is not a known requirement)
"""
import argparse
import ast
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "trace" / "TRACEABILITY.md"
TAG = re.compile(r"\b(HLR-[A-Z]+-\d+|SYS-\d+)((?:/\d+)*)(?:\.\.(\d+))?")


def expand(m):
    """'HLR-ALT-06/07' -> HLR-ALT-06, HLR-ALT-07; 'SYS-1, SYS-6' via findall."""
    base, rest = m.group(1), m.group(2)
    tags = [base]
    prefix = base.rsplit("-", 1)[0]
    width = len(base.rsplit("-", 1)[1])
    for n in filter(None, rest.split("/")):
        tags.append(f"{prefix}-{n.zfill(width)}")
    if m.group(3):  # range, e.g. HLR-DEC-01..06
        lo, hi = int(base.rsplit("-", 1)[1]), int(m.group(3))
        tags = [f"{prefix}-{n:0{width}d}" for n in range(lo, hi + 1)]
    return tags


def tags_in(text):
    out = []
    for m in TAG.finditer(text):
        out += expand(m)
    return out


def parse_sdoc(path):
    reqs = {}
    for block in path.read_text().split("[REQUIREMENT]")[1:]:
        uid = re.search(r"^UID: (\S+)", block, re.M).group(1)
        title = re.search(r"^TITLE: (.+)$", block, re.M).group(1).strip()
        parents = re.findall(r"TYPE: Parent\s*\n\s*VALUE: (\S+)", block)
        reqs[uid] = {"title": title, "parents": parents}
    return reqs


def collect_tests():
    """tag -> sorted list of 'file::test' ids. Module docstrings are ignored
    (they use ranges like HLR-ALT-01..10); only per-test docstrings count."""
    found = {}
    for path in sorted((ROOT / "tests").rglob("test_*.py")):
        tree = ast.parse(path.read_text())
        rel = path.relative_to(ROOT).as_posix()
        for node in ast.walk(tree):
            if isinstance(node, ast.FunctionDef) and node.name.startswith("test_"):
                doc = ast.get_docstring(node) or ""
                for t in tags_in(doc):
                    found.setdefault(t, set()).add(f"{rel}::{node.name}")
    return {k: sorted(v) for k, v in found.items()}


def collect_src():
    found = {}
    for path in sorted((ROOT / "src").glob("*.c")):
        rel = path.relative_to(ROOT).as_posix()
        for lineno, line in enumerate(path.read_text().splitlines(), 1):
            for t in tags_in(line):
                found.setdefault(t, set()).add(f"{rel}:{lineno}")
    return {k: sorted(v) for k, v in found.items()}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()

    sys_reqs = parse_sdoc(ROOT / "reqs" / "system.sdoc")
    hlrs = parse_sdoc(ROOT / "reqs" / "hlr.sdoc")
    tests = collect_tests()
    src = collect_src()
    known = set(sys_reqs) | set(hlrs)

    gaps = []
    children = {s: [h for h, d in hlrs.items() if s in d["parents"]] for s in sys_reqs}

    for h, d in hlrs.items():
        if not d["parents"]:
            gaps.append(f"{h}: no parent SYS requirement")
        if h not in tests:
            gaps.append(f"{h}: no verifying test")
    for s in sys_reqs:
        if not children[s]:
            gaps.append(f"{s}: no decomposing HLR")
        if s not in tests:
            gaps.append(f"{s}: no system-level (integration) test")
    for t in sorted((set(tests) | set(src)) - known):
        gaps.append(f"{t}: tag used in tests/src but not defined in reqs/")

    L = ["# Requirements Traceability Matrix", "",
         "_Generated by `scripts/trace.py` — do not edit by hand._", "",
         "## SYS → HLR → verification", "",
         "| SYS | Title | HLRs | Integration tests |", "|---|---|---|---|"]
    for s, d in sys_reqs.items():
        L.append(f"| {s} | {d['title']} | {', '.join(children[s]) or '**none**'} | "
                 f"{len(tests.get(s, []))} |")
    L += ["", "## HLR → parent, tests, source", "",
          "| HLR | Title | Parent | Unit tests | Source refs |", "|---|---|---|---|---|"]
    for h, d in hlrs.items():
        t = "<br>".join(f"`{x.split('::')[1]}`" for x in tests.get(h, [])) or "**none**"
        sr = ", ".join(f"`{x}`" for x in src.get(h, [])) or "—"
        L.append(f"| {h} | {d['title']} | {', '.join(d['parents']) or '**none**'} | {t} | {sr} |")
    L += ["", "## SYS-level tests", ""]
    for s in sys_reqs:
        for x in tests.get(s, []):
            L.append(f"- {s}: `{x}`")
    L += ["", "## Gaps", ""] + ([f"- {g}" for g in gaps] or ["None."])
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(L) + "\n")

    print(f"{len(hlrs)} HLRs, {len(sys_reqs)} SYS reqs, {len(gaps)} gaps -> {OUT.relative_to(ROOT)}")
    for g in gaps:
        print("GAP:", g)
    if args.check and gaps:
        sys.exit(1)


if __name__ == "__main__":
    main()
